import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.resolve(__dirname, "..");
const extDir = path.join(root, "pi-agent", "extensions");
const outFile = path.join(root, "docs", "EXTENSIONS.md");

function extractDocstring(content) {
  const match = content.match(/\/\*\*([\s\S]*?)\*\//);
  if (!match) return "No description available.";
  return match[1]
    .split("\n")
    .map(line => line.replace(/^\s*\*\s?/, "").trim())
    .filter(line => line.length > 0 && !line.startsWith("@param"))
    .join(" ");
}

function generateDocs() {
  const files = fs.readdirSync(extDir).filter(f => f.endsWith(".js"));
  let md = "# AIIA Pi Extensions API Reference\n\n";
  md += "> ⚠️ This file is auto-generated by `scripts/generate-api-docs.mjs`.\n> Do NOT edit manually. It is verified by `.harness/verify.sh`.\n\n";
  
  for (const file of files.sort()) {
    const content = fs.readFileSync(path.join(extDir, file), "utf8");
    const doc = extractDocstring(content);
    md += `## \`${file}\`\n\n`;
    md += `${doc}\n\n`;
  }
  
  fs.writeFileSync(outFile, md);
  console.log(`[generate-api-docs] Generated ${outFile}`);
}

generateDocs();
